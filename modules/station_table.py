def buoy_name(code: str) -> str:
    """站号 → 中文名（没有就原样返回站号）。"""
    rec = BUOY_STATIONS.get(str(code).strip().upper())
    return rec[0] if rec else str(code)


def buoy_coord(code: str) -> Optional[Tuple[float, float]]:
    """站号 → (经度, 纬度)。"""
    rec = BUOY_STATIONS.get(str(code).strip().upper())
    return (rec[1], rec[2]) if rec else None


def nearest_buoy(lon: float, lat: float) -> Optional[Tuple[str, str, float]]:
    """按坐标找最近的浮标站 → (站号, 中文名, 距离km)。"""
    best = None
    for code, (name, blo, bla) in BUOY_STATIONS.items():
        d = ((blo - lon) ** 2 + (bla - lat) ** 2) ** 0.5 * 111.0
        if best is None or d < best[2]:
            best = (code, name, round(d, 1))
    return best
