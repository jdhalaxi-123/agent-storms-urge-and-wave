def _norm(s: str) -> str:
    return (str(s or "").strip()
            .replace(" ", "").replace("附近", "").replace("海域", "")
            .replace("沿海", "").replace("站", "").replace("市", "").replace("县", ""))


def _match_broad(region: str) -> Optional[str]:
    """匹配大范围区域名（最长优先）。"""
    r = str(region or "")
    if not r:
        return None
    for name in sorted(BROAD_REGIONS.keys(), key=len, reverse=True):
        if name and name in r:
            return name
    return None


def locate(region: str) -> Tuple[Optional[str], Optional[tuple]]:
    """在字典中匹配地点名（最长匹配优先，大小写不敏感）。

    返回 (匹配到的地点名, 坐标) 或 (None, None)。
    """
    r = str(region or "")
    if not r:
        return None, None
    rl = r.lower()
    # 最长名称优先，避免"台湾海峡北部"被"台湾海峡"抢先
    for name in sorted(KNOWN_PLACES.keys(), key=len, reverse=True):
        if name and (name in r or name.lower() in rl):
            return name, KNOWN_PLACES[name]
    # 归一化后再试（去掉"市/县/站/沿海"等后缀）
    r2 = _norm(r)
    if r2:
        for name in sorted(KNOWN_PLACES.keys(), key=len, reverse=True):
            n2 = _norm(name)
            if n2 and n2 in r2:
                return name, KNOWN_PLACES[name]
    return None, None


def in_domain(lon: float, lat: float) -> bool:
    return (LON_MIN <= lon <= LON_MAX) and (LAT_MIN <= lat <= LAT_MAX)


def distance_km(lon1: float, lat1: float, lon2: float, lat2: float) -> float:
    """近似平面距离（km），用于"离最近站点多远"的提示。"""
    dy = (lat2 - lat1) * 111.0
    dx = (lon2 - lon1) * 111.0 * math.cos(math.radians((lat1 + lat2) / 2.0))
    return math.hypot(dx, dy)


def nearest_station(lon: float, lat: float) -> Tuple[str, float]:
    """返回距离该点最近的本站站点名与距离(km)。"""
    best, bestd = "", 1e18
    for name, (lo, la) in SESSION_STATION_COORD.items():
        d = distance_km(lon, lat, lo, la)
        if d < bestd:
            best, bestd = name, d
    return best, round(bestd, 1)


