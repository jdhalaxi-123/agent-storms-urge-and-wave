_NUM = r"[-+]?\d{1,3}(?:\.\d+)?"


def parse_coord(text: str) -> Tuple[Optional[float], Optional[float]]:
    """从自然语言里解析经纬度，返回 (lon, lat) 或 (None, None)。

    支持写法：
        120.5°E, 24.5°N        E120.5 N24.5
        东经120.5 北纬24.5      经度120.5 纬度24.5
        120.5E 24.5N            24.5N 120.5E（自动按数值范围纠正）
        120.5, 24.5（当数值分别落在经纬度量程内时按"经度,纬度"理解）
    """
    s = str(text or "")
    if not s:
        return None, None

    def _f(x: str) -> Optional[float]:
        try:
            return float(x)
        except Exception:
            return None

    # 1) 带 E/W/N/S 或 东经/西经/北纬/南纬 标记
    lon = lat = None
    m = re.search(r"(?:东经|西经|经度|longitude|lon)?\s*(" + _NUM + r")\s*°?\s*(?:E|e|W|w)\b", s)
    if not m:
        m = re.search(r"(?:东经|经度)\s*[:：]?\s*(" + _NUM + r")", s)
    if m:
        lon = _f(m.group(1))
        if "W" in m.group(0).upper() or "西经" in m.group(0):
            lon = -lon if lon is not None else None

    m2 = re.search(r"(?:北纬|南纬|纬度|latitude|lat)?\s*(" + _NUM + r")\s*°?\s*(?:N|n|S|s)\b", s)
    if not m2:
        m2 = re.search(r"(?:北纬|纬度)\s*[:：]?\s*(" + _NUM + r")", s)
    if m2:
        lat = _f(m2.group(1))
        if "S" in m2.group(0).upper() or "南纬" in m2.group(0):
            lat = -lat if lat is not None else None

    if lon is not None or lat is not None:
        return _orient(lon, lat)

    # 2) 纯数字对："120.5 24.5" / "120.5,24.5" / "120.5°/24.5°"
    nums = re.findall(_NUM, s)
    if len(nums) >= 2:
        a, b = _f(nums[0]), _f(nums[1])
        if a is not None and b is not None:
            return _orient(a, b)
    return None, None


def _orient(a: Optional[float], b: Optional[float]) -> Tuple[Optional[float], Optional[float]]:
    """把两个数按"哪个像经度、哪个像纬度"归位。"""
    if a is None or b is None:
        return a, b
    a_lon = LON_MIN - 5 <= a <= LON_MAX + 5
    b_lon = LON_MIN - 5 <= b <= LON_MAX + 5
    a_lat = LAT_MIN - 5 <= a <= LAT_MAX + 5
    b_lat = LAT_MIN - 5 <= b <= LAT_MAX + 5
    if a_lon and b_lat and not (b_lon and a_lat):
        return a, b
    if b_lon and a_lat and not (a_lon and b_lat):
        return b, a
    # 无法区分时：按"经度,纬度"顺序
    return a, b


